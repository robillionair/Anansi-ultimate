//! M7 Slice 1: backup/restore of Product Forge artifacts.
//! The specification pins its source idea set and the
//! source package pins its specification and source set by
//! artifact id; restore must rewrite those references to
//! the restored artifacts (never the source workspace's),
//! fail closed when a referenced artifact is not in the
//! package, and the restored package must still export.

use anansi_core::Core;
use anansi_core::content;
use anansi_core::jobs::ExportSelection;
use anansi_core::readiness::CommandError;
use anansi_core::storage::Storage;
use serde_json::{Value, json};
use std::path::Path;

fn draft(title: &str, body: &str) -> Value {
    json!({ "title": title, "body": body, "privacy": "private",
            "eventDate": null, "validFrom": null, "validUntil": null,
            "confidence": null, "sourceReferences": [] })
}

fn workspace(core: &Core, name: &str) -> String {
    core.workspace_command("create", json!({ "contractVersion": 1, "name": name }))
        .unwrap()["workspace"]["id"]
        .as_str()
        .unwrap()
        .to_string()
}

fn project(core: &Core, ws: &str) -> String {
    core.memory_command(
        "create",
        json!({ "contractVersion": 1, "workspaceId": ws, "kind": "project", "draft": draft("Forge Project", "project") }),
    )
    .unwrap()["memory"]["id"]
        .as_str()
        .unwrap()
        .to_string()
}

fn register(
    core: &Core,
    ws: &str,
    project: &str,
    ty: &str,
    title: &str,
    body: String,
    refs: Vec<String>,
) -> String {
    core.artifacts_command(
        "register",
        json!({
            "contractVersion": 1, "workspaceId": ws, "projectId": project,
            "type": ty, "title": title, "body": body,
            "sourceReferences": refs, "privacy": "private"
        }),
    )
    .unwrap()["artifact"]["artifactId"]
        .as_str()
        .unwrap()
        .to_string()
}

fn spec_body(source_id: &str) -> String {
    json!({
        "format": "anansi-product-spec", "formatVersion": 1,
        "template": "static-web-prototype",
        "sourceArtifactId": source_id, "sourceVersion": 1, "conceptIndex": 0,
        "concept": { "name": "Bean Stock Log" },
        "answers": { "purpose": "p", "intendedUsers": "u", "mustHave": "m" },
        "spec": {
            "title": "Bean Stock Log", "summary": "s", "purpose": "p",
            "intendedUsers": "u", "features": ["a", "b", "c"],
            "pages": ["index.html"], "nonGoals": [], "dataAndState": "local",
            "acceptanceCriteria": ["x", "y"], "openQuestions": []
        }
    })
    .to_string()
}

fn package_body(spec_id: &str, source_id: &str) -> String {
    json!({
        "format": "anansi-source-package", "formatVersion": 1,
        "template": "static-web-prototype",
        "specArtifactId": spec_id, "specVersion": 1,
        "sourceArtifactId": source_id, "sourceVersion": 1,
        "conceptName": "Bean Stock Log",
        "plan": { "summary": "s", "steps": ["a", "b"], "buildNotes": "open index.html", "testingNotes": "not run by ANANSI" },
        "files": [
            { "path": "index.html", "content": "<!doctype html><title>Bean</title>" },
            { "path": "README.md", "content": "# Bean Stock Log\nPrototype." }
        ],
        "limitations": ["Prototype source package generated by a model from a user-approved specification. It has not been built, tested, executed or deployed by ANANSI."]
    })
    .to_string()
}

fn backup_bytes(root: &Path, store: &Storage, ws: &str) -> Vec<u8> {
    let job = store
        .enqueue_export(ws, ExportSelection::Backup { application: false })
        .unwrap();
    let lease = store.claim_export().unwrap().unwrap();
    store.execute_backup(&lease).unwrap();
    let done = store.read_job(ws, &job.id).unwrap();
    let artifact = done.artifact_id.unwrap();
    std::fs::read(
        root.join("exports")
            .join(ws)
            .join(format!("{artifact}.tar")),
    )
    .unwrap()
}

fn upload_once(fresh: &Core, bytes: &[u8], tag: &str) -> (String, String, String, String) {
    let landing = workspace(fresh, &format!("Landing for {tag}"));
    let begin = fresh
        .job_command(
            "upload-begin",
            json!({"contractVersion":1,"workspaceId":landing,"bytes":bytes.len(),
                   "sha256":content::hash(bytes),"plaintextConsent":true}),
        )
        .unwrap();
    let mut job = Value::Null;
    for (index, chunk) in bytes.chunks(65536).enumerate() {
        let offset = index * 65536;
        job = fresh
            .job_command(
                "upload-part",
                json!({"contractVersion":1,"workspaceId":landing,"id":begin["id"],
                       "offset":offset,"bytes":chunk,
                       "finish":offset + chunk.len() == bytes.len()}),
            )
            .unwrap()["job"]
            .clone();
    }
    let preview = fresh
        .job_command(
            "preview",
            json!({"contractVersion":1,"workspaceId":landing,
                   "jobId":job["id"],"artifactId":job["artifactId"]}),
        )
        .unwrap();
    (
        landing,
        job["id"].as_str().unwrap().to_string(),
        job["artifactId"].as_str().unwrap().to_string(),
        preview["sha256"].as_str().unwrap().to_string(),
    )
}

fn restore_job(
    fresh: &Core,
    landing: &str,
    job: &str,
    artifact: &str,
    hash: &str,
    name: &str,
) -> Result<Value, CommandError> {
    fresh.job_command(
        "restore",
        json!({"contractVersion":1,"workspaceId":landing,
               "jobId":job,"artifactId":artifact,"name":name,
               "expectedHash":hash,"confirm":true}),
    )
}

fn try_upload_restore(fresh: &Core, bytes: &[u8], name: &str) -> Result<Value, CommandError> {
    let (landing, job, artifact, hash) = upload_once(fresh, bytes, name);
    restore_job(fresh, &landing, &job, &artifact, &hash, name)
}

#[test]
fn forge_chain_restores_with_remapped_references_and_exports() {
    let dir = tempfile::tempdir().unwrap();
    let core = Core::with_storage_root(dir.path().to_path_buf());
    let source = Storage::new(dir.path().to_path_buf()).unwrap();
    let ws = workspace(&core, "Forge Source");
    let proj = project(&core, &ws);
    let idea = register(
        &core,
        &ws,
        &proj,
        "idea",
        "Idea set",
        "{\"topic\":\"t\",\"concepts\":[]}".to_string(),
        vec![],
    );
    let spec = register(
        &core,
        &ws,
        &proj,
        "specification",
        "Product specification: Bean Stock Log",
        spec_body(&idea),
        vec![format!("artifact://{idea}@v1")],
    );
    let package = register(
        &core,
        &ws,
        &proj,
        "source-package",
        "Source package: Bean Stock Log",
        package_body(&spec, &idea),
        vec![format!("artifact://{spec}@v1")],
    );
    let bytes = backup_bytes(dir.path(), &source, &ws);

    let fresh_dir = tempfile::tempdir().unwrap();
    let fresh = Core::with_storage_root(fresh_dir.path().to_path_buf());
    let restored = try_upload_restore(&fresh, &bytes, "Forge Restored").unwrap();
    let restored_ws = restored["workspaces"][0]["id"]
        .as_str()
        .unwrap()
        .to_string();
    assert_ne!(restored_ws, ws);

    // Find the restored trio in the restored project.
    let projects = fresh
        .memory_command(
            "list",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "kind": "project" }),
        )
        .unwrap();
    let restored_project = projects["memories"][0]["id"].as_str().unwrap().to_string();
    let list = fresh
        .artifacts_command(
            "list",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "projectId": restored_project }),
        )
        .unwrap();
    let by_type = |ty: &str| {
        list["artifacts"]
            .as_array()
            .unwrap()
            .iter()
            .find(|a| a["type"] == ty)
            .unwrap()["artifactId"]
            .as_str()
            .unwrap()
            .to_string()
    };
    let (r_idea, r_spec, r_package) = (
        by_type("idea"),
        by_type("specification"),
        by_type("source-package"),
    );
    assert_ne!(r_spec, spec);
    assert_ne!(r_package, package);

    let read = |id: &str| {
        fresh
            .artifacts_command(
                "read",
                json!({ "contractVersion": 1, "workspaceId": restored_ws, "artifactId": id, "version": 1 }),
            )
            .unwrap()
    };
    let spec_doc: Value = serde_json::from_str(read(&r_spec)["body"].as_str().unwrap()).unwrap();
    assert_eq!(spec_doc["sourceArtifactId"], r_idea);
    let package_doc: Value =
        serde_json::from_str(read(&r_package)["body"].as_str().unwrap()).unwrap();
    assert_eq!(package_doc["specArtifactId"], r_spec);
    assert_eq!(package_doc["sourceArtifactId"], r_idea);
    // The registry reference column remapped too.
    let package_record = list["artifacts"]
        .as_array()
        .unwrap()
        .iter()
        .find(|a| a["type"] == "source-package")
        .unwrap();
    assert_eq!(
        package_record["sourceReferences"][0],
        format!("artifact://{r_spec}@v1")
    );
    // The restored package still exports, citing the
    // restored specification in its manifest.
    let export = fresh
        .artifacts_command(
            "forge-export",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "artifactId": r_package, "version": 1 }),
        )
        .unwrap();
    assert_eq!(
        export["files"],
        json!(["ANANSI-PACKAGE.json", "index.html", "README.md"])
    );
    // Original workspace untouched.
    let original: Value = serde_json::from_str(&read_original(&core, &ws, &package)).unwrap();
    assert_eq!(original["specArtifactId"], spec);
}

fn read_original(core: &Core, ws: &str, id: &str) -> String {
    core.artifacts_command(
        "read",
        json!({ "contractVersion": 1, "workspaceId": ws, "artifactId": id, "version": 1 }),
    )
    .unwrap()["body"]
        .as_str()
        .unwrap()
        .to_string()
}

#[test]
fn package_citing_an_absent_specification_fails_the_restore_closed() {
    let dir = tempfile::tempdir().unwrap();
    let core = Core::with_storage_root(dir.path().to_path_buf());
    let source = Storage::new(dir.path().to_path_buf()).unwrap();
    let ws = workspace(&core, "Forge Broken");
    let proj = project(&core, &ws);
    let idea = register(
        &core,
        &ws,
        &proj,
        "idea",
        "Idea set",
        "{\"topic\":\"t\",\"concepts\":[]}".to_string(),
        vec![],
    );
    // The cited specification is not an artifact of this
    // workspace (it lives nowhere in the backup).
    register(
        &core,
        &ws,
        &proj,
        "source-package",
        "Source package: Bean Stock Log",
        package_body("ffffffffffffffffffffffffffffffff", &idea),
        vec![],
    );
    let bytes = backup_bytes(dir.path(), &source, &ws);
    let fresh_dir = tempfile::tempdir().unwrap();
    let fresh = Core::with_storage_root(fresh_dir.path().to_path_buf());
    let result = try_upload_restore(&fresh, &bytes, "Forge Broken Restored");
    assert!(result.is_err(), "restore must fail closed: {result:?}");
    // Nothing was materialized beyond the landing workspace.
    let all = fresh
        .workspace_command("list", json!({ "contractVersion": 1 }))
        .unwrap();
    assert_eq!(all["workspaces"].as_array().unwrap().len(), 1);
}

#[test]
fn specification_approval_transfers_to_the_restored_version_only() {
    let dir = tempfile::tempdir().unwrap();
    let core = Core::with_storage_root(dir.path().to_path_buf());
    let source = Storage::new(dir.path().to_path_buf()).unwrap();
    let ws = workspace(&core, "Forge Approval Source");
    let proj = project(&core, &ws);
    let idea = register(
        &core,
        &ws,
        &proj,
        "idea",
        "Idea set",
        "{\"topic\":\"t\",\"concepts\":[]}".to_string(),
        vec![],
    );
    let spec = register(
        &core,
        &ws,
        &proj,
        "specification",
        "Product specification: Bean Stock Log",
        spec_body(&idea),
        vec![format!("artifact://{idea}@v1")],
    );
    let approval = core
        .ai_command(
            "forge-spec-approve",
            json!({ "contractVersion": 1, "workspaceId": ws, "projectId": proj,
                    "specArtifactId": spec, "specVersion": 1 }),
        )
        .unwrap();
    assert_eq!(approval["approved"], true);
    assert_eq!(approval["alreadyApproved"], false);
    let bytes = backup_bytes(dir.path(), &source, &ws);

    let fresh_dir = tempfile::tempdir().unwrap();
    let fresh = Core::with_storage_root(fresh_dir.path().to_path_buf());
    let restored = try_upload_restore(&fresh, &bytes, "Forge Approval Restored").unwrap();
    let restored_ws = restored["workspaces"][0]["id"]
        .as_str()
        .unwrap()
        .to_string();
    let projects = fresh
        .memory_command(
            "list",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "kind": "project" }),
        )
        .unwrap();
    let restored_project = projects["memories"][0]["id"].as_str().unwrap().to_string();
    let list = fresh
        .artifacts_command(
            "list",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "projectId": restored_project }),
        )
        .unwrap();
    let by_type = |ty: &str| {
        list["artifacts"]
            .as_array()
            .unwrap()
            .iter()
            .find(|a| a["type"] == ty)
            .unwrap()
            .clone()
    };
    let r_spec = by_type("specification");
    let r_spec_id = r_spec["artifactId"].as_str().unwrap().to_string();
    let r_approval = by_type("specification-approval");
    let r_approval_id = r_approval["artifactId"].as_str().unwrap().to_string();
    assert_ne!(
        r_approval_id,
        approval["approvalArtifactId"].as_str().unwrap()
    );
    let approval_body: Value = serde_json::from_str(
        fresh
            .artifacts_command(
                "read",
                json!({ "contractVersion": 1, "workspaceId": restored_ws, "artifactId": r_approval_id, "version": 1 }),
            )
            .unwrap()["body"]
            .as_str()
            .unwrap(),
    )
    .unwrap();
    // The approval now points at the restored specification
    // version and approves its recomputed content hash —
    // not the source workspace's id or hash.
    assert_eq!(approval_body["specArtifactId"], r_spec_id);
    assert_eq!(approval_body["specVersion"], 1);
    assert_eq!(approval_body["specContentHash"], r_spec["contentHash"]);
    assert_ne!(approval_body["specArtifactId"], spec);
    // Status in the restored workspace agrees: v1 is
    // approved there without any re-approval.
    let status = fresh
        .ai_command(
            "forge-spec-approval-status",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "projectId": restored_project,
                    "specArtifactId": r_spec_id, "specVersion": 1 }),
        )
        .unwrap();
    assert_eq!(status["approved"], true);
    assert_eq!(status["approvalArtifactId"], r_approval_id);
}

#[test]
fn revised_package_version_restores_with_remapped_parent_reference() {
    // A Slice 2 revised version (same artifact, v2, with
    // parent fields) restores with its parent reference
    // remapped to the restored package id.
    let dir = tempfile::tempdir().unwrap();
    let core = Core::with_storage_root(dir.path().to_path_buf());
    let source = Storage::new(dir.path().to_path_buf()).unwrap();
    let ws = workspace(&core, "Forge Revised Source");
    let proj = project(&core, &ws);
    let idea = register(
        &core,
        &ws,
        &proj,
        "idea",
        "Idea set",
        "{\"topic\":\"t\",\"concepts\":[]}".to_string(),
        vec![],
    );
    let spec = register(
        &core,
        &ws,
        &proj,
        "specification",
        "Product specification: Bean Stock Log",
        spec_body(&idea),
        vec![format!("artifact://{idea}@v1")],
    );
    let package = register(
        &core,
        &ws,
        &proj,
        "source-package",
        "Source package: Bean Stock Log",
        package_body(&spec, &idea),
        vec![format!("artifact://{spec}@v1")],
    );
    let mut revised: Value = serde_json::from_str(&package_body(&spec, &idea)).unwrap();
    revised["parentPackageArtifactId"] = json!(package);
    revised["parentPackageVersion"] = json!(1);
    revised["revisionInstructions"] = json!("Update the heading.");
    revised["files"] = json!([
        { "path": "index.html", "content": "<!doctype html><title>Bean — revised</title>" },
        { "path": "README.md", "content": "# Bean Stock Log\nPrototype." }
    ]);
    core.artifacts_command(
        "revise",
        json!({
            "contractVersion": 1, "workspaceId": ws,
            "artifactId": package, "expectedVersion": 1,
            "title": "Source package: Bean Stock Log", "body": revised.to_string(),
            "sourceReferences": [format!("artifact://{spec}@v1")]
        }),
    )
    .unwrap();
    let bytes = backup_bytes(dir.path(), &source, &ws);

    let fresh_dir = tempfile::tempdir().unwrap();
    let fresh = Core::with_storage_root(fresh_dir.path().to_path_buf());
    let restored = try_upload_restore(&fresh, &bytes, "Forge Revised Restored").unwrap();
    let restored_ws = restored["workspaces"][0]["id"]
        .as_str()
        .unwrap()
        .to_string();
    let projects = fresh
        .memory_command(
            "list",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "kind": "project" }),
        )
        .unwrap();
    let restored_project = projects["memories"][0]["id"].as_str().unwrap().to_string();
    let list = fresh
        .artifacts_command(
            "list",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "projectId": restored_project }),
        )
        .unwrap();
    let r_package = list["artifacts"]
        .as_array()
        .unwrap()
        .iter()
        .find(|a| a["type"] == "source-package")
        .unwrap();
    let r_package_id = r_package["artifactId"].as_str().unwrap().to_string();
    let r_spec = list["artifacts"]
        .as_array()
        .unwrap()
        .iter()
        .find(|a| a["type"] == "specification")
        .unwrap();
    let r_spec_id = r_spec["artifactId"].as_str().unwrap().to_string();
    let read = fresh
        .artifacts_command(
            "read",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "artifactId": r_package_id, "version": 2 }),
        )
        .unwrap();
    let doc: Value = serde_json::from_str(read["body"].as_str().unwrap()).unwrap();
    assert_eq!(doc["parentPackageArtifactId"], r_package_id);
    assert_eq!(doc["parentPackageVersion"], 1);
    assert_eq!(doc["revisionInstructions"], "Update the heading.");
    assert_eq!(doc["specArtifactId"], r_spec_id);
    // The restored v2 still exports.
    let export = fresh
        .artifacts_command(
            "forge-export",
            json!({ "contractVersion": 1, "workspaceId": restored_ws, "artifactId": r_package_id, "version": 2 }),
        )
        .unwrap();
    assert!(
        export["files"]
            .as_array()
            .unwrap()
            .iter()
            .any(|p| p == "index.html")
    );
}
