// Generates packages/ui/src/somniaCompactionBenchmark.ts from the frozen
// SOMNIA compaction benchmark fixtures in
// crates/core/tests/fixtures/somnia-compaction/.
//
// The generated module carries only the records and questions the UI needs
// to import a case (oracle metadata such as forbiddenRetained stays in the
// fixture files). Every fixture file is verified against the benchmark
// MANIFEST SHA-256 before it is embedded, so a changed fixture fails the
// generation instead of silently shipping different data.
//
// Usage: node scripts/generate-somnia-compaction-benchmark.mjs
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fixtureDir = join(root, 'crates/core/tests/fixtures/somnia-compaction');
const outPath = join(root, 'packages/ui/src/somniaCompactionBenchmark.ts');

const manifest = JSON.parse(await readFile(join(fixtureDir, 'MANIFEST.json'), 'utf8'));
const manifestByFile = new Map(manifest.files.map(entry => [entry.file, entry.sha256]));

const files = (await readdir(fixtureDir))
  .filter(name => /^case-\d{3}\.json$/.test(name))
  .sort();
if (files.length !== manifest.caseCount) {
  throw new Error(`Expected ${manifest.caseCount} cases, found ${files.length}.`);
}

const cases = [];
for (const file of files) {
  const bytes = await readFile(join(fixtureDir, file));
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  if (manifestByFile.get(file) !== sha256) {
    throw new Error(`${file} does not match the benchmark MANIFEST hash.`);
  }
  const parsed = JSON.parse(bytes.toString('utf8'));
  cases.push({
    id: parsed.id,
    category: parsed.category,
    records: parsed.records,
    questions: parsed.questions.map(question => ({
      id: question.id,
      text: question.text,
      expectedAnswer: question.expectedAnswer ?? null,
    })),
  });
}

const header = `// GENERATED by scripts/generate-somnia-compaction-benchmark.mjs from the
// frozen SOMNIA compaction benchmark fixtures
// (crates/core/tests/fixtures/somnia-compaction/, MANIFEST caseCount ${manifest.caseCount}).
// Do not edit by hand; regenerate after any fixture change.
import type { CompactionQuestion, SomniaCompactionRecord } from '@anansi/contracts';

export type SomniaCompactionBenchmarkCase = {
  id: string;
  category: string;
  records: SomniaCompactionRecord[];
  questions: CompactionQuestion[];
};

`;

await writeFile(
  outPath,
  header +
    `export const SOMNIA_COMPACTION_BENCHMARK_CASES: SomniaCompactionBenchmarkCase[] = ` +
    JSON.stringify(cases, null, 2) +
    ';\n',
);
console.log(`Wrote ${cases.length} frozen cases to ${outPath}`);
